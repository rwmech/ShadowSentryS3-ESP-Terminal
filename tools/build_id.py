#!/usr/bin/env python3
"""Write main/gz/build_id.h: the git short hash and the build date (fork addition, subsys).

esp_app_get_description()->version is git describe, taken when CMake configures
the project. PlatformIO's incremental builds do not reconfigure, so it goes
stale (a build of 80500fb said 0e7fe48). This header is rewritten on every
PlatformIO build instead, and only when its text changes, so an unchanged
commit and day recompile nothing. The front panel's SUBSYS screen reads it.

  #define SS_BUILD_HASH "1bf46c5"        (with "-dirty" for uncommitted changes
                                           to tracked files; "unknown" without git)
  #define SS_BUILD_DATE "2026-11-03"     (local date of the build)

Runs from three places:
  - platformio.ini, as a pre: extra_script (every PlatformIO build);
  - main/CMakeLists.txt, at configure time (idf.py build; refreshed when CMake
    reconfigures);
  - by hand: python tools/build_id.py
"""
import datetime
import os
import subprocess
import sys


def git(root, *args):
    try:
        r = subprocess.run(["git", "-C", root] + list(args), capture_output=True,
                           text=True, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return None
    return r.stdout.strip() if r.returncode == 0 else None


def build(root):
    h = git(root, "rev-parse", "--short=7", "HEAD")
    if h:
        dirty = git(root, "status", "--porcelain", "--untracked-files=no")
        if dirty:
            h += "-dirty"
    else:
        h = "unknown"
    date = datetime.date.today().isoformat()
    text = ("/* Generated by tools/build_id.py: do not edit, not in git. */\n"
            "#pragma once\n"
            f"#define SS_BUILD_HASH \"{h}\"\n"
            f"#define SS_BUILD_DATE \"{date}\"\n")
    out_dir = os.path.join(root, "main", "gz")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "build_id.h")
    try:
        with open(path, "r", encoding="ascii") as f:
            if f.read() == text:
                return
    except OSError:
        pass
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    print(f"build_id: {h} {date}")


try:
    Import("env")  # noqa: F821  (PlatformIO pre: script)
    build(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:
    if __name__ == "__main__":
        build(sys.argv[1] if len(sys.argv) > 1 else
              os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
