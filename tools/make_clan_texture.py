"""Make the clan skin's metal tile: main/ui/ui_clan_tex.c (fork addition, Robert Mech).

A 64 x 64 weathered gunmetal tile in RGB565 (LVGL's LV_IMG_CF_TRUE_COLOR with
LV_COLOR_16_SWAP=n, both boards): mottling, a horizontal brushed grain, a few
scratches and rust specks. Every part is periodic over 64 px (noise filtered
in the frequency domain, scratches drawn modulo 64), so the tile repeats with
no seams. The panel tiles it as the screen's background (bg_img_tiled).

Usage: python -I tools/make_clan_texture.py   (numpy; seed fixed, so the
output only changes when this script does)
"""
import os
import sys

import numpy as np

N = 64
SEED = 1918
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "main", "ui", "ui_clan_tex.c")

BASE = np.array([0x2e, 0x2b, 0x28], float)      # gunmetal, between the preview's #34302c and #211f1d
RUST = np.array([0x6b, 0x3a, 0x24], float)      # the preview's --rust


def periodic_noise(rng, fx, fy):
    """White noise low-passed with a Gaussian of widths fx, fy (cycles per tile)."""
    w = rng.standard_normal((N, N))
    kx = np.fft.fftfreq(N) * N
    ky = np.fft.fftfreq(N) * N
    g = np.exp(-(kx[None, :] / fx) ** 2 - (ky[:, None] / fy) ** 2)
    n = np.real(np.fft.ifft2(np.fft.fft2(w) * g))
    return n / (np.abs(n).max() or 1.0)


def main():
    rng = np.random.default_rng(SEED)
    mottle = periodic_noise(rng, 3.0, 3.0)        # soft light and dark patches
    grain = periodic_noise(rng, 2.0, 24.0)        # brushed: long along x, fine across y
    fine = periodic_noise(rng, 32.0, 32.0)        # tooth
    lum = 9.0 * mottle + 5.0 * grain + 2.5 * fine

    # Scratches: thin lines, wrapped, lighter (worn edge) or darker (groove)
    for _ in range(5):
        x0, y0 = rng.uniform(0, N, 2)
        ang = rng.uniform(-0.5, 0.5) + (0 if rng.random() < 0.7 else np.pi / 2)
        length = rng.uniform(10, 30)
        amp = rng.choice([6.0, -5.0])
        for t in np.linspace(0, length, int(length * 3)):
            x = int(x0 + t * np.cos(ang)) % N
            y = int(y0 + t * np.sin(ang)) % N
            lum[y, x] += amp * (1.0 - 0.5 * t / length)

    img = BASE[None, None, :] + lum[:, :, None]

    # Rust: a few warm specks where the mottling is dark
    rust = np.clip(periodic_noise(rng, 5.0, 5.0) - 0.35, 0, None) * np.clip(-mottle + 0.3, 0, 1)
    a = np.clip(rust * 0.9, 0, 0.3)[:, :, None]
    img = img * (1 - a) + RUST[None, None, :] * a

    img = np.clip(np.rint(img), 0, 255).astype(np.uint16)
    r, g, b = img[:, :, 0], img[:, :, 1], img[:, :, 2]
    px = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    data = px.astype("<u2").tobytes()          # little endian: LV_COLOR_16_SWAP=n

    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 16]) + ",")
    src = f"""// Generated by tools/make_clan_texture.py: the clan skin's {N} x {N} metal tile, RGB565.
// Do not edit; change the script and run it again.

#include "lvgl.h"

#if LV_COLOR_DEPTH != 16 || LV_COLOR_16_SWAP
#error "ui_clan_tex.c is RGB565 without the byte swap (tools/make_clan_texture.py)"
#endif

static const uint8_t ui_clan_tex_map[] = {{
{chr(10).join(lines)}
}};

const lv_img_dsc_t ui_clan_tex = {{
    .header.cf = LV_IMG_CF_TRUE_COLOR,
    .header.always_zero = 0,
    .header.w = {N},
    .header.h = {N},
    .data_size = sizeof(ui_clan_tex_map),
    .data = ui_clan_tex_map,
}};
"""
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write(src)
    lo, hi = int(px.min()), int(px.max())
    print(f"{os.path.normpath(OUT)}: {len(data)} B, RGB565 0x{lo:04x}..0x{hi:04x}, "
          f"mean RGB {img.reshape(-1, 3).mean(0).round(1).tolist()}")


if __name__ == "__main__":
    sys.exit(main())
